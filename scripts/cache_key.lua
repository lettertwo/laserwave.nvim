-- Generates lua/laserwave/cache_key.lua: a hash of every module that can
-- affect the cached colorscheme. Run with `make cache-key`.
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
local out = root .. "/lua/laserwave/cache_key.lua"

local paths = {}
for _, path in ipairs(vim.fn.globpath(root .. "/lua/laserwave", "**/*.lua", true, true)) do
  local rel = path:sub(#root + 2)
  if rel ~= "lua/laserwave/cache_key.lua" and not rel:match("_spec%.lua$") then
    table.insert(paths, rel)
  end
end
table.sort(paths)

local parts = {}
for _, rel in ipairs(paths) do
  local f = assert(io.open(root .. "/" .. rel, "rb"))
  table.insert(parts, rel .. "\0" .. f:read("*a") .. "\0")
  f:close()
end
local hash = vim.fn.sha256(table.concat(parts))

local content = '-- Generated by `make cache-key`. Do not edit.\nreturn "' .. hash .. '"\n'

local f = io.open(out, "rb")
local current = f and f:read("*a")
if f then
  f:close()
end
if current ~= content then
  local w = assert(io.open(out, "wb"))
  w:write(content)
  w:close()
end
io.stdout:write(hash .. "\n")
